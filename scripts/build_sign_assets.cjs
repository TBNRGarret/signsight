/* Derive Flutter PNGs and browser lookup from reviewed, checked-in SVG originals. No network. */
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {chromium}=require('playwright');
async function main(){
 const root=path.resolve(__dirname,'..'),source=path.join(root,'frontend/shared/signs'),out=path.join(root,'mobile/assets/signs');
 const raw=fs.readFileSync(path.join(source,'catalog.json'),'utf8'),catalog=JSON.parse(raw);
 const keys=new Set();for(const row of catalog.entries){
  if(!/^[a-z0-9_]+$/.test(row.key)||row.svg!==row.key+'.svg'||keys.has(row.key))throw Error('Unsafe or duplicated asset key');
  keys.add(row.key);
  if(crypto.createHash('sha256').update(fs.readFileSync(path.join(source,row.svg))).digest('hex')!==row.source.sha256)throw Error('Approved SVG changed: '+row.key);
 }
 fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch(process.env.PLAYWRIGHT_CHANNEL?{channel:process.env.PLAYWRIGHT_CHANNEL}:{ });
 try{
  const page=await browser.newPage();
  await page.setContent('<!doctype html><html><body></body></html>');
  for(const row of [...catalog.entries,{key:'unknown',svg:'unknown.svg'}]){
   const svg=fs.readFileSync(path.join(source,row.svg),'utf8');
   const encoded=await page.evaluate(async svg=>{
    const image=new Image(),url=URL.createObjectURL(new Blob([svg],{type:'image/svg+xml'}));
    try{image.src=url;await image.decode();const canvas=document.createElement('canvas');canvas.width=canvas.height=192;
     const scale=Math.min(192/image.naturalWidth,192/image.naturalHeight),width=image.naturalWidth*scale,height=image.naturalHeight*scale;
     canvas.getContext('2d').drawImage(image,(192-width)/2,(192-height)/2,width,height);return canvas.toDataURL('image/png').split(',')[1];
    }finally{URL.revokeObjectURL(url)}
   },svg);
   fs.writeFileSync(path.join(out,row.key+'.png'),Buffer.from(encoded,'base64'));
  }
 }finally{await browser.close()}
 fs.writeFileSync(path.join(out,'catalog.json'),raw);
 const serialized=JSON.stringify(catalog).replace(/</g,'\\u003c');
 fs.writeFileSync(path.join(root,'frontend/shared/sign_registry.js'),
  '/* Generated by scripts/build_sign_assets.cjs; edit approved catalog.json instead. */\n'+
  '(function(root){const data='+serialized+';if(typeof module!=="undefined"&&module.exports)module.exports=data;else root.signSightSignRegistry=data;})(typeof window==="undefined"?globalThis:window);\n');
 fs.copyFileSync(path.join(source,'LICENSE.md'),path.join(out,'LICENSE.md'));
 console.log('Generated '+(catalog.entries.length+1)+' local PNGs, browser registry and Flutter catalogue.');
}
main().catch(error=>{console.error(error);process.exitCode=1});
